def recommend_products_lift(
    product_name,
    top_n=5,
    min_copurchases=5
):
    # Localizar o produto de origem
    resultado = catalogo[
        catalogo["ProductName"].str.casefold()
        == product_name.casefold()
    ]

    if resultado.empty:
        print(f"Produto não encontrado: {product_name}")
        return pd.DataFrame()

    product_id = resultado.iloc[0]["ProductID"]

    # Selecionar todas as conexões do produto
    recomendacoes = conexoes[
        (conexoes["ProductID_A"] == product_id)
        | (conexoes["ProductID_B"] == product_id)
    ].copy()

    if recomendacoes.empty:
        print("Não existem recomendações para este produto.")
        return pd.DataFrame()

    # Exigir uma frequência mínima de compras conjuntas
    recomendacoes = recomendacoes[
        recomendacoes["CoPurchaseCount"] >= min_copurchases
    ].copy()

    if recomendacoes.empty:
        print(
            "Nenhuma associação atingiu a frequência mínima. "
            "Tente reduzir min_copurchases."
        )
        return pd.DataFrame()

    # Identificar o produto recomendado em cada par
    recomendacoes["RecommendedProductID"] = recomendacoes.apply(
        lambda linha: (
            linha["ProductID_B"]
            if linha["ProductID_A"] == product_id
            else linha["ProductID_A"]
        ),
        axis=1
    )

    # Recuperar o nome e a categoria do produto recomendado
    recomendacoes = recomendacoes.merge(
        catalogo[
            ["ProductID", "ProductName", "Category", "UnitPrice"]
        ],
        left_on="RecommendedProductID",
        right_on="ProductID",
        how="left"
    )

    # Ordenar primeiro por Lift e depois pela frequência conjunta
    recomendacoes = recomendacoes.sort_values(
        ["Lift", "CoPurchaseCount"],
        ascending=[False, False]
    )

    return recomendacoes[
        [
            "ProductName",
            "Category",
            "UnitPrice",
            "CoPurchaseCount",
            "Lift"
        ]
    ].head(top_n).reset_index(drop=True).rename(
        columns={
            "ProductName": "RecommendedProduct",
            "UnitPrice": "Price"
        }
    )


