def recommend_products(product_name, top_n=5):
    # Localizar o ID do produto pelo nome
    resultado = catalogo[
        catalogo["ProductName"].str.casefold()
        == product_name.casefold()
    ]

    if resultado.empty:
        print(f"Produto não encontrado: {product_name}")
        return pd.DataFrame()

    product_id = resultado.iloc[0]["ProductID"]

    # Verificar se o produto está no grafo
    if product_id not in G:
        print("Produto não encontrado no grafo.")
        return pd.DataFrame()

    # Obter os produtos conectados e a frequência da relação
    vizinhos = G[product_id]

    recomendacoes = []

    for vizinho_id, atributos in vizinhos.items():
        produto = catalogo[
            catalogo["ProductID"] == vizinho_id
        ].iloc[0]

        recomendacoes.append({
            "ProductID": vizinho_id,
            "RecommendedProduct": produto["ProductName"],
            "Category": produto["Category"],
            "Price": produto["UnitPrice"],
            "CoPurchaseCount": atributos["weight"]
        })

    # Converter as recomendações em uma tabela
    resultado_recomendacoes = pd.DataFrame(recomendacoes)

    if resultado_recomendacoes.empty:
        print("Não existem recomendações para este produto.")
        return resultado_recomendacoes

    # Ordenar pelas relações mais frequentes
    resultado_recomendacoes = (
        resultado_recomendacoes
        .sort_values(
            "CoPurchaseCount",
            ascending=False
        )
        .head(top_n)
        .reset_index(drop=True)
    )

    return resultado_recomendacoes


