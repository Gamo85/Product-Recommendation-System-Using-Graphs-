from itertools import combinations

# Criar um grafo não direcionado
G = nx.Graph()

# Adicionar todos os produtos como nós
for _, produto in catalogo.iterrows():
    G.add_node(
        produto["ProductID"],
        name=produto["ProductName"],
        category=produto["Category"],
        price=produto["UnitPrice"]
    )

# Percorrer cada pedido e conectar os produtos comprados juntos
for order_id, grupo in itens_pedido.groupby("OrderID"):

    # Evitar repetir o mesmo produto dentro do pedido
    produtos_pedido = grupo["ProductID"].unique()

    # Criar todos os pares possíveis de produtos do pedido
    for produto_a, produto_b in combinations(produtos_pedido, 2):

        # Se a conexão já existe, aumentar seu peso
        if G.has_edge(produto_a, produto_b):
            G[produto_a][produto_b]["weight"] += 1

        # Caso contrário, criar uma nova conexão
        else:
            G.add_edge(
                produto_a,
                produto_b,
                weight=1
            )

print("Grafo criado com sucesso!")
print("Total de nós:", G.number_of_nodes())
print("Total de arestas:", G.number_of_edges())

